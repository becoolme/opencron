-- PostgreSQL baseline. Application timestamps remain integer Unix seconds.
-- Better Auth core tables for PostgreSQL.
CREATE TABLE "user" (
  id TEXT PRIMARY KEY NOT NULL,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  "emailVerified" BOOLEAN NOT NULL DEFAULT FALSE,
  image TEXT,
  "createdAt" TIMESTAMPTZ NOT NULL,
  "updatedAt" TIMESTAMPTZ NOT NULL
);

CREATE TABLE session (
  id TEXT PRIMARY KEY NOT NULL,
  "expiresAt" TIMESTAMPTZ NOT NULL,
  token TEXT NOT NULL UNIQUE,
  "createdAt" TIMESTAMPTZ NOT NULL,
  "updatedAt" TIMESTAMPTZ NOT NULL,
  "ipAddress" TEXT,
  "userAgent" TEXT,
  "userId" TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE
);

CREATE INDEX session_userId_idx ON session("userId");

CREATE TABLE account (
  id TEXT PRIMARY KEY NOT NULL,
  issuer TEXT NOT NULL,
  "accountId" TEXT NOT NULL,
  "providerId" TEXT NOT NULL,
  "userId" TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  "accessToken" TEXT,
  "refreshToken" TEXT,
  "idToken" TEXT,
  "accessTokenExpiresAt" TIMESTAMPTZ,
  "refreshTokenExpiresAt" TIMESTAMPTZ,
  scope TEXT,
  password TEXT,
  "createdAt" TIMESTAMPTZ NOT NULL,
  "updatedAt" TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX account_issuer_accountId_uidx ON account(issuer, "accountId");
CREATE INDEX account_userId_idx ON account("userId");

CREATE TABLE verification (
  id TEXT PRIMARY KEY NOT NULL,
  identifier TEXT NOT NULL,
  value TEXT NOT NULL,
  "expiresAt" TIMESTAMPTZ NOT NULL,
  "createdAt" TIMESTAMPTZ NOT NULL,
  "updatedAt" TIMESTAMPTZ NOT NULL
);

CREATE INDEX verification_identifier_idx ON verification(identifier);


CREATE TABLE jobs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  url TEXT,
  method TEXT NOT NULL DEFAULT 'GET',
  headers TEXT,
  body TEXT,
  cron TEXT NOT NULL,
  enabled INTEGER NOT NULL DEFAULT 1,
  timeout_ms INTEGER NOT NULL DEFAULT 30000,
  next_run_at BIGINT NOT NULL,
  last_run_at BIGINT,
  last_status TEXT,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  type TEXT NOT NULL DEFAULT 'url',
  script TEXT,
  script_version INTEGER NOT NULL DEFAULT 1,
  notify_targets TEXT,
  last_notified_at BIGINT,
  owner_user_id TEXT REFERENCES "user"(id) ON DELETE CASCADE
);
CREATE INDEX idx_jobs_due ON jobs(enabled, next_run_at);
CREATE INDEX jobs_owner_user_id_idx ON jobs(owner_user_id);
CREATE TABLE executions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id INTEGER NOT NULL,
  started_at BIGINT NOT NULL,
  duration_ms INTEGER NOT NULL,
  status_code INTEGER,
  ok INTEGER NOT NULL,
  error TEXT,
  response_snippet TEXT
);
CREATE INDEX idx_exec_job_time ON executions(job_id, started_at DESC);
CREATE INDEX idx_exec_time ON executions(started_at);
CREATE TABLE script_storage (
  owner_user_id TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  job_id INTEGER NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  key TEXT NOT NULL,
  value TEXT NOT NULL,
  updated_at BIGINT NOT NULL,
  PRIMARY KEY (owner_user_id, job_id, key)
);
CREATE INDEX script_storage_job_idx ON script_storage(job_id);
-- Sandboxed records dedicated to Dynamic Worker scripts.
-- The parent Worker injects owner_user_id and job_id; scripts only control
-- record_key and the string data field through a structured RPC API.
CREATE TABLE script_records (
  owner_user_id TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  job_id INTEGER NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  record_key TEXT NOT NULL,
  data TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  PRIMARY KEY (owner_user_id, job_id, record_key)
);

CREATE INDEX script_records_job_idx ON script_records(job_id);
